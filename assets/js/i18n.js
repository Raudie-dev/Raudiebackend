class RauDieI18n {
  constructor() {
    this.currentLang = this.detectLanguage();
    this.init();
  }

  detectLanguage() {
    // 1. URL parameter: ?lang=en or ?lang=es
    const urlParams = new URLSearchParams(window.location.search);
    const langParam = urlParams.get('lang');
    if (langParam && (langParam === 'es' || langParam === 'en')) {
      return langParam;
    }

    // 2. localStorage
    const saved = localStorage.getItem('raudie_lang');
    if (saved && (saved === 'es' || saved === 'en')) {
      return saved;
    }

    // 3. Browser language
    const browserLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
    if (browserLang.startsWith('en')) {
      return 'en';
    }

    // Default to Spanish
    return 'es';
  }

  init() {
    this.applyLanguage(this.currentLang);
    this.bindEvents();
  }

  applyLanguage(lang) {
    if (!RAUDIE_TRANSLATIONS[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('raudie_lang', lang);

    document.documentElement.setAttribute('lang', lang);

    const dict = RAUDIE_TRANSLATIONS[lang];

    // Translate all data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        // If translation contains HTML tags (e.g. <span> or <strong>), use innerHTML
        if (dict[key].includes('<') && dict[key].includes('>')) {
          el.innerHTML = dict[key];
        } else {
          el.textContent = dict[key];
        }
      }
    });

    // Translate placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // Update switcher active states
    document.querySelectorAll('.lang-btn').forEach((btn) => {
      const btnLang = btn.getAttribute('data-lang');
      if (btnLang === lang) {
        btn.classList.add('active');
        btn.setAttribute('aria-pressed', 'true');
      } else {
        btn.classList.remove('active');
        btn.setAttribute('aria-pressed', 'false');
      }
    });

    // Dispatch custom event for reactive components
    window.dispatchEvent(new CustomEvent('raudie:langChange', { detail: { lang } }));
  }

  bindEvents() {
    document.addEventListener('click', (e) => {
      const btn = e.target.closest('.lang-btn');
      if (btn) {
        e.preventDefault();
        const targetLang = btn.getAttribute('data-lang');
        if (targetLang && targetLang !== this.currentLang) {
          this.applyLanguage(targetLang);
        }
      }
    });
  }
}

// Initialize on DOM ready
document.addEventListener('DOMContentLoaded', () => {
  window.raudieI18n = new RauDieI18n();
});
